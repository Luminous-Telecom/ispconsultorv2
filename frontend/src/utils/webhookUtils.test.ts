import {
  buildWebhookUrlErp,
  isAutoGeneratedEfiWebhookUrl,
  resolveBancoUrlRetorno,
} from './webhookUtils';

jest.mock('../config/api', () => ({
  API_CONFIG: {
    get WEBHOOK_BASE_URL() {
      return 'https://erp.exemplo.com';
    },
  },
}));

describe('resolveBancoUrlRetorno', () => {
  it('mostra a URL salva em vez de regenerar', () => {
    expect(
      resolveBancoUrlRetorno('efi', 'http://localhost:3000/webhook/efi', 7)
    ).toBe('http://localhost:3000/webhook/efi');
  });

  it('sugere webhook do ERP quando a URL salva está vazia', () => {
    expect(resolveBancoUrlRetorno('asaas', '', 12)).toBe(
      'https://erp.exemplo.com/webhook/asaas/12'
    );
    expect(resolveBancoUrlRetorno('bancario', '   ')).toBe('');
  });

  it('sugere URL Efi com identificador da conta quando disponível', () => {
    expect(
      resolveBancoUrlRetorno('efi', '', 7, '56108d6083041be4cb6573d088ffe4aa')
    ).toBe(
      'https://erp.exemplo.com/webhook/efi/56108d6083041be4cb6573d088ffe4aa'
    );
  });
});

describe('buildWebhookUrlErp', () => {
  it('prioriza payee_code na URL Efi', () => {
    expect(buildWebhookUrlErp('efi', 9, 'abc123')).toBe(
      'https://erp.exemplo.com/webhook/efi/abc123'
    );
  });
});

describe('isAutoGeneratedEfiWebhookUrl', () => {
  it('reconhece sugestões automáticas sem payee_code', () => {
    expect(isAutoGeneratedEfiWebhookUrl('https://erp.exemplo.com/webhook/efi')).toBe(true);
    expect(isAutoGeneratedEfiWebhookUrl('https://erp.exemplo.com/webhook/efi/5', 5)).toBe(true);
    expect(
      isAutoGeneratedEfiWebhookUrl(
        'https://erp.exemplo.com/webhook/efi/56108d6083041be4cb6573d088ffe4aa'
      )
    ).toBe(false);
  });
});
