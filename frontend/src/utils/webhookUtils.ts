import { API_CONFIG } from '../config/api';

function absoluteWebhookPath(path: string): string {
  if (/^https?:\/\//i.test(path)) return path;
  const base = API_CONFIG.WEBHOOK_BASE_URL;
  const normalized = path.startsWith('/') ? path : `/${path}`;
  return base ? `${base}${normalized}` : normalized;
}

/**
 * Ex.: https://dominio.com/webhook/efi/56108d60... (payee_code)
 * ou https://dominio.com/webhook/efi/42 (id do banco, fallback)
 */
export function buildWebhookUrlErp(
  tipo: 'efi' | 'asaas',
  bancoId?: number | null,
  accountIdentifier?: string | null
): string {
  const account = typeof accountIdentifier === 'string' ? accountIdentifier.trim() : '';
  if (tipo === 'efi' && account) {
    return absoluteWebhookPath(`/webhook/${tipo}/${encodeURIComponent(account)}`);
  }
  const suffix = bancoId != null ? `/${bancoId}` : '';
  return absoluteWebhookPath(`/webhook/${tipo}${suffix}`);
}

/** Ex: https://dominio.com/webhook/efi/saas */
export function buildWebhookUrlSaas(tipo: 'efi' | 'asaas'): string {
  return absoluteWebhookPath(`/webhook/${tipo}/saas`);
}

/** Prefere a URL salva no banco; só gera sugestão se estiver vazia. */
export function resolveBancoUrlRetorno(
  tipo: string | undefined | null,
  urlSalva: string | null | undefined,
  bancoId?: number | null,
  accountIdentifier?: string | null
): string {
  const salva = typeof urlSalva === 'string' ? urlSalva.trim() : '';
  if (salva) return salva;
  if (tipo === 'efi' || tipo === 'asaas') {
    return buildWebhookUrlErp(tipo, bancoId, accountIdentifier);
  }
  return '';
}

/** URL ainda é a sugestão automática (sem payee_code / só id). */
export function isAutoGeneratedEfiWebhookUrl(
  url: string | null | undefined,
  bancoId?: number | null
): boolean {
  if (!url || !url.trim()) return true;
  try {
    const path = url.includes('://') ? new URL(url).pathname : url;
    const normalized = path.replace(/\/+$/, '');
    if (normalized === '/webhook/efi') return true;
    if (bancoId != null && normalized === `/webhook/efi/${bancoId}`) return true;
    if (/^\/webhook\/efi\/\d+$/.test(normalized)) return true;
    return false;
  } catch {
    return false;
  }
}
